import numpy as np
import pandas as pd
from datetime import datetime, timedelta

# Fixação da semente para fins de reprodutibilidade científica (NBC TA 230 / 530)
np.random.seed(232029597)  # Semente parametrizada com o número da sua matrícula

N_REGISTROS = 500000

# Saldo exato da subconta 'Veículos' do Imobilizado Consolidado em 31/12/2025 (Nota 12)
# R$ 22.972.473 mil = R$ 22.972.473.000,00
SALDO_META_LIQUIDO = 22972473000.00

print(f"Gerando base analítica sintética da Frota com {N_REGISTROS:,} registros...")

# 1. Identificadores únicos dos bens
chassis_simulados = [f"9BGMOV25{i:09d}" for i in range(1, N_REGISTROS + 1)]
placas = [f"MOV{i:04d}" for i in range(1, N_REGISTROS + 1)]

# 2. Segmentos de atuação (proporção reportada nas DFs: RAC e GTF)
segmentos = np.random.choice(["RAC", "GTF"], size=N_REGISTROS, p=[0.40, 0.60])

# 3. Modelos automotivos representativos da frota
modelos_lista = [
    "VW Polo Track 1.0",
    "Fiat Argo Drive 1.0",
    "Hyundai HB20 Comfort 1.0",
    "Chevrolet Onix Plus LT 1.0T",
    "Jeep Renegade Longitude 1.3T",
    "Toyota Corolla XEi 2.0",
    "Fiat Strada Freedom 1.3",
]
modelos = np.random.choice(modelos_lista, size=N_REGISTROS)

# 4. Datas de Ativação no Imobilizado (entre 01/01/2023 e 31/12/2025)
inicio_periodo = datetime(2023, 1, 1)
dias_decorridos = np.random.randint(0, 365 * 3, size=N_REGISTROS)
datas_aquisicao = np.array([
    (inicio_periodo + timedelta(days=int(d))).strftime("%Y-%m-%d")
    for d in dias_decorridos
])

# 5. Custo original de aquisição estimado por unidade
# Tickets médios de compra reportados: ~R$ 96 mil a R$ 107 mil
custos = np.random.normal(loc=98000, scale=18000, size=N_REGISTROS)
custos = np.clip(custos, 55000, 240000)

# 6. Depreciação acumulada (taxa média consolidada de 8,05% a.a. conforme Nota 12)
percentual_depreciacao = np.random.uniform(0.02, 0.22, size=N_REGISTROS)
depreciacao = custos * percentual_depreciacao
valor_liquido = custos - depreciacao

# 7. Conciliação matemática exata com o saldo contábil da Nota 12
fator_conciliacao = SALDO_META_LIQUIDO / np.sum(valor_liquido)
custos = np.round(custos * fator_conciliacao, 2)
depreciacao = np.round(depreciacao * fator_conciliacao, 2)
valor_liquido = np.round(custos - depreciacao, 2)

# Correção de resíduo de arredondamento no primeiro item
diferenca_arredondamento = SALDO_META_LIQUIDO - np.sum(valor_liquido)
valor_liquido[0] = np.round(valor_liquido[0] + diferenca_arredondamento, 2)

# 8. Injeção de Inconsistências / Erros Controlados para o PT 530
# A. 40 registros com saldo contábil líquido negativo
idx_negativos = np.random.choice(range(100, N_REGISTROS), size=40, replace=False)
valor_liquido[idx_negativos] = -2500.00

# B. 30 registros com data de aquisição posterior ao encerramento (Cut-off inválido)
idx_data_invalida = np.random.choice(range(1000, N_REGISTROS), size=30, replace=False)
datas_aquisicao[idx_data_invalida] = "2026-02-20"

# C. 25 duplicidades de Chassi (Duplicidade física no imobilizado)
idx_duplicados = np.random.choice(range(5000, N_REGISTROS), size=25, replace=False)
for idx in idx_duplicados:
    chassis_simulados[idx] = chassis_simulados[0]

# Construção do DataFrame estruturado
df_frota = pd.DataFrame({
    "CHASSI_ID": chassis_simulados,
    "PLACA": placas,
    "SEGMENTO": segmentos,
    "MODELO": modelos,
    "DATA_AQUISICAO": datas_aquisicao,
    "VALOR_CUSTO": custos,
    "DEPRECIACAO_ACUM": depreciacao,
    "VALOR_LIQUIDO": valor_liquido
})

# Exportação para arquivo CSV
nome_arquivo = "base_simulada_frota_movida_2025.csv"
df_frota.to_csv(nome_arquivo, index=False)

print("Base gerada com êxito!")
print(f"Total de Registros: {len(df_frota):,}")
print(f"Saldo Contábil Teórico Meta: R$ {SALDO_META_LIQUIDO:,.2f}")
print(f"Saldo da Base Gerada: R$ {df_frota['VALOR_LIQUIDO'].sum():,.2f}")

